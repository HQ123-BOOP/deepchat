/** 继续最后一条未完成的回答：保留原消息与开关，仅将新流的内容追加到原块之后。 */
export const continueReply = (sessionId: string, messageId: string) => {
  if (get().importingHistory || deletingSessions.has(sessionId)) {
    return
  }
  const session = getSession(sessionId)
  if (!session || getStreamController(sessionId)) {
    return
  }
  const path = getVisibleMessages(session)
  const question = path.at(-2)
  const previous = path.at(-1)
  if (
    question?.role !== 'user' ||
    previous?.role !== 'assistant' ||
    previous.id !== messageId ||
    !canContinueReply(previous)
  ) {
    return
  }
  const { reasoningEffort, search } = useSettings.getState()
  const thinking = reasoningEffort !== 'off'
  const reply: AssistantMessage = {
    ...previous,
    // 未记录请求配置的回复，续写时使用默认模型和当前开关。
    model: previous.model ?? useSettings.getState().provider.model,
    thinking: previous.thinking ?? thinking,
    search: previous.search ?? search,
    status: 'pending',
    stopReason: undefined,
    stopDetails: undefined,
    error: undefined,
  }
  updateReply(sessionId, reply)
  updateSession(sessionId, (s) => ({ ...s, updatedAt: Date.now() }))
  persist(sessionId)
  void streamReply(sessionId, reply, { history: path.slice(0, -2), question, prefix: previous })
}

/** 附件补传失败后重试：保留原回答位置，重新补传并请求 */
export const retryUpload = (sessionId: string, messageId: string) => {
  if (get().importingHistory || deletingSessions.has(sessionId)) {
    return
  }
  const session = getSession(sessionId)
  if (!session || getStreamController(sessionId)) {
    return
  }
  const path = getVisibleMessages(session)
  const index = path.findIndex((message) => message.id === messageId)
  const question = path[index - 1]
  const previous = path[index]
  if (
    question?.role !== 'user' ||
    previous?.role !== 'assistant' ||
    previous.error?.kind !== 'upload'
  ) {
    return
  }
  const reply: AssistantMessage = { ...previous, status: 'pending', error: undefined }
  updateReply(sessionId, reply)
  persist(sessionId)
  void streamReply(sessionId, reply, { history: path.slice(0, index - 1), question })
}

type Request = { history: Message[]; question: UserMessage; prefix?: AssistantMessage }

/** 把本地 Blob 转成不含 data: 前缀的 base64，供标准 Chat API 的 image_url 块使用 */
const blobToBase64 = (blob: Blob): Promise<string> =>
  new Promise((resolve, reject) => {
    const reader = new FileReader()
    reader.onload = () => resolve(String(reader.result).split(',')[1] ?? '')
    reader.onerror = () => reject(reader.error ?? new Error('读取图片失败'))
    reader.readAsDataURL(blob)
  })

type PreparedAttachments = {
  images: ProviderImage[]
  refs: AttachmentRef[]
  fileNames: Record<string, string>
}

/**
 * 附件全部留在本地：图片内联成 base64 直接送进模型，其余只登记清单，
 * 由模型通过 ocr_file 工具按需读取，不再预先上传 Files API 或预处理 OCR。
 */
const prepareAttachments = async (
  files: FileAttachment[],
  signal: AbortSignal
): Promise<PreparedAttachments> => {
  const images: ProviderImage[] = []
  const refs: AttachmentRef[] = []
  const fileNames: Record<string, string> = {}
  for (const file of files) {
    fileNames[file.id] = file.name
    refs.push({ id: file.id, name: file.name, isImage: file.isImage })
    if (!file.isImage || file.size > MAX_INLINE_IMAGE_BYTES) {
      continue
    }
    const blob = await db.loadFile(file.id)
    if (!blob) {
      continue
    }
    const mimeType = file.mimeType || blob.type
    if (!/^image\/(jpeg|png|gif|webp)$/i.test(mimeType)) {
      continue
    }
    signal.throwIfAborted()
    images.push({ data: await blobToBase64(blob), mimeType })
  }
  return { images, refs, fileNames }
}

/**
 * 请求并消费流：统一由 pi-ai 发出，工具调用在本地 ReAct 循环里执行。
 * 流式增量按动画帧刷新内存，完成、失败或停止后落盘。
 */
const streamReply = async (sessionId: string, initial: AssistantMessage, request: Request) => {
  const controller = new AbortController()
  set((state) => ({ streaming: { ...state.streaming, [sessionId]: controller } }))
  let reply = initial
  let frame = 0
  const flush = () => {
    cancelAnimationFrame(frame)
    frame = 0
    updateReply(sessionId, reply)
  }
  streamFlushes.set(sessionId, flush)

  try {
    const settings = useSettings.getState()
    const provider = createConfiguredPiProvider()
    const { images, refs, fileNames } = await prepareAttachments(
      request.question.files,
      controller.signal
    )
    // 视觉模型直接理解图片，纯图片时不给 OCR；只要有文档，或模型读不了图片，就需要解析
    const acceptsImages = modelAcceptsImages(
      settings.provider.piProvider,
      settings.provider.model,
      settings.provider.inputModalities
    )
    const hasDocuments = refs.some((ref) => !ref.isImage)
    const needsOcr = refs.length > 0 && (hasDocuments || !acceptsImages)
    const toolSchemas = [
      ...(initial.search ? WEB_TOOL_SCHEMAS : []),
      ...(needsOcr ? [OCR_TOOL_SCHEMA, READ_TOOL_SCHEMA] : []),
    ]
    // 身份、当前时间、位置、平台与语言；每次请求按本地时区重新生成
    const systemPrompt = createSystemPrompt({
      provider: settings.provider.piProvider,
      model: settings.provider.model,
      locale: settings.locale,
      location: settings.location,
    })
    const messages = await buildProviderMessages({
      provider,
      model: settings.provider.model,
      systemPrompt,
      history: request.history,
      question: request.question,
      budget: { window: 131072, maxOutput: 8192 },
      tools: toolSchemas,
      images,
      attachments: refs,
      signal: controller.signal,
    })
    reply = await runProviderReply({
      provider,
      model: settings.provider.model,
      messages,
      tools: toolSchemas,
      // 工具 API 与模型请求共用一个 Key；旧版本单独保存的 Key 作为回退
      toolApiKey: settings.provider.apiKey.trim() || settings.apiKey || '',
      loadFile: db.loadFile,
      saveFileText: db.saveFileText,
      loadFileText: db.loadFileText,
      fileNames,
      reply,
      signal: controller.signal,
      reasoningEffort: settings.reasoningEffort,
      onChange: (next) => {
        reply = next
        if (document.visibilityState === 'hidden') {
          flush()
        } else {
          frame ||= requestAnimationFrame(flush)
        }
      },
      onDone: (next) => {
        reply = next
      },
    })
  } catch (error) {
    if (controller.signal.aborted) {
      reply = settleReply(reply, 'stopped', Date.now())
    } else {
      reply = settleReply(reply, 'error', Date.now(), {
        kind: 'protocol',
        message: error instanceof Error ? error.message : String(error),
      })
    }
  } finally {
    streamFlushes.delete(sessionId)
    cancelAnimationFrame(frame)
    updateReply(sessionId, reply)
    set((state) => ({
      streaming: Object.fromEntries(
        Object.entries(state.streaming).filter(([id]) => id !== sessionId)
      ),
    }))
    persist(sessionId)
  }
}
